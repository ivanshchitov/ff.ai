#!/bin/bash
set -euo pipefail
# Запускает llama-server там, куда приложение обращается за локальными пресетами:
# хост и порт совпадают со значением по умолчанию `FFAI_LOCAL_API_URL`, поэтому приложение
# не ищет сервер по адресу — оно ждёт его именно здесь.
#
# `--models-max 1` держит в памяти одну модель: роутер поднимает выбранный пресет, а не весь
# список, иначе 16 ГБ общей памяти кончаются на втором пресете.
# `--models-preset` — путь рядом со скриптом, а не относительно текущего каталога: приложение
# запускает скрипт из целевого репозитория, где никакого `llama_server/` нет.

# Каталог скрипта: абсолютный путь, чтобы запускать из любого рабочего каталога.
SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)

exec llama-server \
    --host 127.0.0.1 \
    --port 9999 \
    --ui \
    --models-max 1 \
    --models-preset "$SCRIPT_DIR"/models.ini
